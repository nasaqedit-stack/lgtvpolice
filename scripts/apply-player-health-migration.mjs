#!/usr/bin/env node
/**
 * Applies supabase/migrations/20261008010000_player_health.sql to the production database.
 *
 * Why this exists: the self-healing telemetry the player reports every heartbeat (player_state,
 * boot_count, recovery_count, the command versions the television actually executed) is written to
 * columns this migration adds. The application keeps working without them — every read falls back
 * to the base columns — but a screen's own state is then invisible: "cachedMediaCount: 0" cannot be
 * told apart from "the player never booted", and nobody can prove a fix reached the device.
 *
 * The migration is written with `add column if not exists`, so running it twice is harmless: this
 * script is idempotent and prints the columns it found afterwards.
 *
 * Usage (GitHub Actions; needs the Production environment secrets):
 *   node scripts/apply-player-health-migration.mjs
 *
 * Locally it degrades: without SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY it prints the
 * instructions instead of inventing credentials.
 */
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import path from 'node:path';

const MIGRATION = 'supabase/migrations/20261008010000_player_health.sql';
const COLUMNS = [
  'player_state', 'player_state_since', 'last_applied_sync_version', 'last_applied_reload_version',
  'recovery_count', 'last_recovery_at', 'last_recovery_reason', 'last_recovery_state',
  'last_health_status', 'last_health_checked_at', 'last_boot_at', 'boot_count',
];

function projectRefFromUrl(url) {
  const match = /^https:\/\/([^.]+)\.supabase\.(co|in|net)/.exec(String(url || ''));
  return match ? match[1] : null;
}

function connectionString() {
  if (process.env.SUPABASE_DB_URL) return process.env.SUPABASE_DB_URL;
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const ref = projectRefFromUrl(url);
  if (!url || !key || !ref) return null;
  // The key is generated by Supabase and can contain characters that have to be escaped in a URI.
  const user = encodeURIComponent('postgres');
  const password = encodeURIComponent(key);
  const host = process.env.SUPABASE_DB_HOST || `db.${ref}.supabase.co`;
  const port = process.env.SUPABASE_DB_PORT || '5432';
  return `postgresql://${user}:${password}@${host}:${port}/postgres?sslmode=require`;
}

function psql(args) {
  return execFileSync('psql', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

function main() {
  const file = path.join(process.cwd(), MIGRATION);
  if (!existsSync(file)) {
    console.error(`missing migration file: ${MIGRATION}`);
    process.exitCode = 1;
    return;
  }
  const dsn = connectionString();
  if (!dsn) {
    console.log('No Supabase credentials in the environment. Run this from the');
    console.log('"Apply player-health migration" workflow (environment: Production), or set');
    console.log('SUPABASE_DB_URL (or SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY) yourself:');
    console.log('  node scripts/apply-player-health-migration.mjs');
    process.exitCode = 2;
    return;
  }

  console.log(`applying ${MIGRATION} …`);
  try {
    const output = psql([dsn, '-v', 'ON_ERROR_STOP=1', '-f', file]);
    if (output && output.trim()) console.log(output.trim());
  } catch (error) {
    console.error('the migration failed:');
    console.error(String((error && error.stderr) || (error && error.message) || error).slice(0, 4000));
    process.exitCode = 1;
    return;
  }

  const list = COLUMNS.map((name) => `'${name}'`).join(', ');
  const query = `select column_name from information_schema.columns` +
    ` where table_schema = 'public' and table_name = 'screens' and column_name in (${list}) order by column_name;`;
  const present = psql([dsn, '-t', '-A', '-c', query])
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
  const missing = COLUMNS.filter((name) => !present.includes(name));

  console.log(`player-health columns present: ${present.length}/${COLUMNS.length}`);
  if (missing.length) {
    console.error(`MISSING: ${missing.join(', ')}`);
    process.exitCode = 1;
    return;
  }
  console.log('all player-health columns are present; the player telemetry has somewhere to land.');
}

main();
